import { HttpClient, HttpResponse } from '@angular/common/http';
import { Injectable, inject } from '@angular/core';
import { Observable, map } from 'rxjs';

import { ExportFileType } from '../models/api.models';
import { saveBlob } from '../utils/files';
import { ApiService, QueryParams, toHttpParams } from './api.service';

export interface EmailExportRequest {
  file_type: ExportFileType;
  recipients: string[];
  subject?: string;
  message?: string;
}

/**
 * Talks to the backend export endpoints that every table exposes:
 *   GET  <endpoint>export/?file_type=pdf|xlsx&<filters>
 *   POST <endpoint>export/email/?<filters>
 * The files are generated by Django; the browser only downloads them.
 */
@Injectable({ providedIn: 'root' })
export class ExportService {
  private readonly http = inject(HttpClient);
  private readonly api = inject(ApiService);

  download(endpoint: string, fileType: ExportFileType, params: QueryParams): Observable<string> {
    return this.http
      .get(this.api.url(`${endpoint}export/`), {
        params: toHttpParams({ ...params, file_type: fileType }),
        responseType: 'blob',
        observe: 'response',
      })
      .pipe(
        map((response: HttpResponse<Blob>) => {
          const filename = filenameFrom(response.headers.get('Content-Disposition'), fileType);
          saveBlob(response.body as Blob, filename);
          return filename;
        }),
      );
  }

  email(endpoint: string, params: QueryParams, body: EmailExportRequest): Observable<{ message: string }> {
    return this.api.post<{ message: string }>(`${endpoint}export/email/`, body, params);
  }
}

function filenameFrom(header: string | null, fileType: ExportFileType): string {
  const match = header?.match(/filename="?([^";]+)"?/i);
  return match?.[1] ?? `export.${fileType}`;
}
